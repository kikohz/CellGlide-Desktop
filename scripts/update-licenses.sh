#!/usr/bin/env bash
# Regenerates crates/cg-gui/assets/third-party-licenses.txt, the list the About page shows
# and the packages install as THIRD-PARTY-LICENSES.txt. Run it whenever Cargo.lock changes
# (the cg-gui test `licenses_are_not_older_than_cargo_lock` fails until you do), and as part
# of the release checklist.
#
# Needs cargo-about 0.9.2:  cargo install --locked cargo-about --features cli
#
# File layout: line 1 is a header holding the FNV-1a 64 checksum of Cargo.lock; then the
# crates cargo-about finds (packaging/licenses/about.toml); then the C code cargo-about cannot
# see: hev-socks5-tunnel and what it bundles (crates/hev-sys/hev, git submodules), libyaml
# (its upstream notice is kept in packaging/licenses/libyaml-License.txt, because hev's own
# yaml/License only names hev), and the distinct per-file license notices of the bundled C
# sources (scripts/extract-notices.py).
#
# Release checklist (M5): re-run this after any Cargo.lock change, which includes a version
# bump of a workspace crate (the workspace version is recorded in Cargo.lock), and commit the
# result.
set -euo pipefail
cd "$(dirname "$0")/.."

out=crates/cg-gui/assets/third-party-licenses.txt

# Everything is checked and built first; the real file is replaced only by a complete result,
# so a missing tool can never leave it empty.
die() {
  echo "update-licenses.sh: $*" >&2
  exit 1
}
trap 'echo "update-licenses.sh: failed at line $LINENO; $out left as it was" >&2' ERR
command -v python3 >/dev/null 2>&1 || die "python3 is not on PATH"
cargo about --version >/dev/null 2>&1 ||
  die "cargo-about is missing (cargo install --locked cargo-about --features cli)"

tmp=$(mktemp)
new=$(mktemp)
trap 'rm -f "$tmp" "$new"' EXIT

cargo about generate --workspace --locked \
  --config packaging/licenses/about.toml packaging/licenses/about.hbs -o "$tmp"

hev=crates/hev-sys/hev
{
  python3 -I - <<'PY'
import pathlib

h = 0xCBF29CE484222325
for byte in pathlib.Path("Cargo.lock").read_bytes():
    h = ((h ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
print(f"# Generated by scripts/update-licenses.sh; Cargo.lock fnv1a64 {h:016x}")
PY
  echo "CellGlide third-party licenses"
  echo
  cat "$tmp"
  for entry in \
    "hev-socks5-tunnel|$hev/LICENSE" \
    "hev-socks5-tunnel (core)|$hev/src/core/LICENSE" \
    "lwIP|$hev/third-part/lwip/LICENSE" \
    "hev-task-system|$hev/third-part/hev-task-system/LICENSE" \
    "yaml (hev's copy)|$hev/third-part/yaml/License" \
    "libyaml|packaging/licenses/libyaml-License.txt"; do
    echo "================================================================================"
    echo "${entry%%|*}"
    echo
    cat "${entry#*|}"
    echo
  done
  # The license comment of every bundled C source (lwIP carries PPP, polarssl, 6LoWPAN... code
  # with other holders' BSD terms), each distinct text once, with the files it came from.
  # hev-task-system and yaml are included so a notice that appears there later is not missed.
  python3 -I scripts/extract-notices.py "$hev/third-part" lwip/src hev-task-system yaml
} >"$new"

# A complete file starts with the header and holds the crates and the C notices.
head -n 1 "$new" | grep -q "^# Generated by scripts/update-licenses.sh; Cargo.lock fnv1a64 " ||
  die "the generated list has no header; $out left as it was"
[ -s "$tmp" ] || die "cargo about produced nothing; $out left as it was"
[ "$(wc -l <"$new")" -gt 1000 ] || die "the generated list is too short; $out left as it was"
# Copied, not moved: the file keeps its own permissions rather than mktemp's 0600.
cat "$new" >"$out"
wc -c "$out"
